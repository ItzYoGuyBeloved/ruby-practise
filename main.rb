# Ruby practice file
# This file is for learning the fundamentals of Ruby.

puts "Hello, Ruby!"

# Variables and data types
name = "Beloved"
age = 21
is_student = true

puts "Name: #{name}"
puts "Age: #{age}"
puts "Student: #{is_student}"

# Arithmetic operators
num1 = 10
num2 = 5

puts "Addition: #{num1 + num2}"
puts "Subtraction: #{num1 - num2}"
puts "Multiplication: #{num1 * num2}"
puts "Division: #{num1 / num2}"
puts "Modulo: #{num1 % num2}"

# Comparison operators
puts "Equal? #{num1 == num2}"
puts "Greater than? #{num1 > num2}"
puts "Less than? #{num1 < num2}"

# Logical operators
puts "AND: #{(num1 > 0) && (num2 > 0)}"
puts "OR: #{(num1 > 0) || (num2 < 0)}"
puts "NOT: #{!(num1 == num2)}"
